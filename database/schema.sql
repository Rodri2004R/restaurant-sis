-- Función RPC para registrar movimientos manuales de inventario de forma atómica con soporte de compra_id
CREATE OR REPLACE FUNCTION public.registrar_movimiento_inventario(
    p_producto_id uuid,
    p_tipo_movimiento varchar,
    p_cantidad integer,
    p_motivo text,
    p_compra_id uuid DEFAULT NULL
)
RETURNS uuid
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
    v_user_id uuid;
    v_admin_id uuid;
    v_prod_exists uuid;
    v_inv_id uuid;
    v_stock_anterior numeric(12,2);
    v_stock_posterior numeric(12,2);
    v_costo_unitario numeric(10,2);
    v_kardex_id uuid;
    v_compra_estado varchar(30);
    v_cant_comprada integer;
BEGIN
    -- 1. Validar autenticación y permisos de Administrador activo
    v_user_id := auth.uid();
    IF v_user_id IS NULL THEN
        RAISE EXCEPTION 'No se ha detectado una sesión autenticada válida.';
    END IF;

    SELECT p.id INTO v_admin_id
    FROM public.perfiles p
    JOIN public.roles r ON r.id = p.rol_id
    WHERE p.id = v_user_id
      AND p.estado = TRUE
      AND r.nombre = 'Administrador';

    IF v_admin_id IS NULL THEN
        RAISE EXCEPTION 'Solo un Administrador puede registrar movimientos manuales de inventario.';
    END IF;

    -- 2. Validar tipo de movimiento manual permitido
    IF p_tipo_movimiento NOT IN ('ajuste_entrada', 'ajuste_salida', 'merma', 'consumo', 'devolucion_proveedor') THEN
        RAISE EXCEPTION 'Tipo de movimiento no permitido para operaciones manuales: %', p_tipo_movimiento;
    END IF;

    -- 3. Validar cantidad entera positiva
    IF p_cantidad IS NULL OR p_cantidad <= 0 THEN
        RAISE EXCEPTION 'La cantidad del movimiento debe ser un número entero mayor a 0.';
    END IF;

    -- 4. Validar motivo obligatorio (mínimo 3 caracteres no vacíos)
    IF p_motivo IS NULL OR length(trim(p_motivo)) < 3 THEN
        RAISE EXCEPTION 'El motivo es obligatorio y debe contener al menos 3 caracteres.';
    END IF;

    -- 5. Validaciones de compra_id según el tipo de movimiento
    IF p_tipo_movimiento = 'devolucion_proveedor' THEN
        -- p_compra_id es obligatorio para devolucion_proveedor
        IF p_compra_id IS NULL THEN
            RAISE EXCEPTION 'Para una devolución a proveedor se requiere especificar el identificador de la compra (p_compra_id).';
        END IF;

        -- Verificar que la compra exista y esté en estado 'Registrada' (no 'Anulada')
        SELECT estado INTO v_compra_estado
        FROM public.compras
        WHERE id = p_compra_id;

        IF v_compra_estado IS NULL THEN
            RAISE EXCEPTION 'La compra especificada no existe en la base de datos.';
        END IF;

        IF v_compra_estado = 'Anulada' THEN
            RAISE EXCEPTION 'No se puede realizar una devolución sobre una compra que ha sido anulada.';
        END IF;

        -- Verificar que el producto pertenezca a la compra indicada y consultar cantidad comprada
        SELECT cantidad INTO v_cant_comprada
        FROM public.detalles_compra
        WHERE compra_id = p_compra_id
          AND producto_id = p_producto_id;

        IF v_cant_comprada IS NULL THEN
            RAISE EXCEPTION 'El producto indicado no pertenece al detalle de la compra especificada.';
        END IF;

        -- Verificar que la cantidad a devolver no supere la cantidad comprada original
        IF p_cantidad > v_cant_comprada THEN
            RAISE EXCEPTION 'La cantidad a devolver (%) no puede superar la cantidad comprada en el comprobante (%).', p_cantidad, v_cant_comprada;
        END IF;
    ELSE
        -- Para ajuste_entrada, ajuste_salida, merma y consumo, p_compra_id DEBE ser NULL
        IF p_compra_id IS NOT NULL THEN
            RAISE EXCEPTION 'El parámetro p_compra_id solo debe proporcionarse para movimientos de tipo devolucion_proveedor.';
        END IF;
    END IF;

    -- 6. Validar existencia del producto en el catálogo
    SELECT id INTO v_prod_exists
    FROM public.productos
    WHERE id = p_producto_id;

    IF v_prod_exists IS NULL THEN
        RAISE EXCEPTION 'El producto especificado no existe en el catálogo.';
    END IF;

    -- 7. Localizar y bloquear la fila de inventario para concurrencia segura (FOR UPDATE)
    SELECT id, COALESCE(stock_actual, 0), COALESCE(costo_unitario, 0.00)
    INTO v_inv_id, v_stock_anterior, v_costo_unitario
    FROM public.inventario
    WHERE producto_id = p_producto_id
    FOR UPDATE;

    IF v_inv_id IS NULL THEN
        RAISE EXCEPTION 'El producto no tiene registro de inventario.';
    END IF;

    -- 8. Calcular stock resultante y evitar stock negativo en operaciones de salida
    IF p_tipo_movimiento = 'ajuste_entrada' THEN
        v_stock_posterior := v_stock_anterior + p_cantidad;
    ELSE
        -- ajuste_salida, merma, consumo, devolucion_proveedor
        IF v_stock_anterior < p_cantidad THEN
            RAISE EXCEPTION 'Stock insuficiente para realizar el movimiento. Stock actual: %, solicitado: %', v_stock_anterior, p_cantidad;
        END IF;
        v_stock_posterior := v_stock_anterior - p_cantidad;
    END IF;

    -- 9. Actualizar inventario (únicamente stock_actual y updated_at)
    UPDATE public.inventario
    SET stock_actual = v_stock_posterior,
        updated_at = NOW()
    WHERE id = v_inv_id;

    -- 10. Insertar movimiento en Kardex (inmutable, append-only)
    INSERT INTO public.kardex (
        producto_id,
        tipo_movimiento,
        cantidad,
        stock_anterior,
        stock_posterior,
        costo_unitario,
        motivo,
        usuario_id,
        compra_id,
        pedido_id,
        created_at
    ) VALUES (
        p_producto_id,
        p_tipo_movimiento,
        p_cantidad,
        v_stock_anterior,
        v_stock_posterior,
        v_costo_unitario,
        trim(p_motivo),
        v_user_id,
        p_compra_id,
        NULL,
        NOW()
    )
    RETURNING id INTO v_kardex_id;

    RETURN v_kardex_id;
END;
$$;

