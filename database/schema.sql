REVOKE EXECUTE ON FUNCTION public.registrar_salida_venta(uuid) FROM anon;
GRANT EXECUTE ON FUNCTION public.registrar_salida_venta(uuid) TO authenticated;
GRANT EXECUTE ON FUNCTION public.registrar_salida_venta(uuid) TO service_role;

