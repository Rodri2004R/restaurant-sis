-- ==============================================================================
-- 1. TABLA: ROLES (US-003)
-- ==============================================================================
CREATE TABLE IF NOT EXISTS public.roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(50) NOT NULL UNIQUE,
    descripcion TEXT,
    estado BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

COMMENT ON TABLE public.roles IS 'Catálogo de roles de acceso del personal del restaurante y comensales';

-- ==============================================================================
-- 2. TABLA: PERFILES DE USUARIO (US-001 & US-002)
-- Relacionada directamente con auth.users de Supabase
-- ==============================================================================
CREATE TABLE IF NOT EXISTS public.perfiles (
    id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    rol_id BIGINT NOT NULL REFERENCES public.roles(id) ON DELETE RESTRICT DEFAULT 1,
    nombre VARCHAR(100) NOT NULL,
    apellido VARCHAR(100) NOT NULL,
    email VARCHAR(255),
    ci VARCHAR(30),
    telefono VARCHAR(30),
    estado BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

COMMENT ON TABLE public.perfiles IS 'Información de perfil complementaria vinculada a la cuenta de Supabase Auth';

-- ==============================================================================
-- 3. TABLA: CLIENTES (US-004)
-- ==============================================================================
CREATE TABLE IF NOT EXISTS public.clientes (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    nombre VARCHAR(100) NOT NULL,
    apellido VARCHAR(100) NOT NULL,
    documento VARCHAR(30) NOT NULL UNIQUE,
    telefono VARCHAR(30),
    email VARCHAR(255),
    estado BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

COMMENT ON TABLE public.clientes IS 'Directorio de clientes del restaurante para historial y reservas';

-- ==============================================================================
-- 4. TABLA: MESAS (US-005 / Gestión de Distribución)
-- ==============================================================================
CREATE TABLE IF NOT EXISTS public.mesas (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    numero INTEGER NOT NULL UNIQUE CHECK (numero > 0),
    capacidad INTEGER NOT NULL CHECK (capacidad > 0),
    ubicacion VARCHAR(50) NOT NULL DEFAULT 'Salón Principal',
    estado VARCHAR(30) NOT NULL DEFAULT 'disponible' 
        CHECK (estado IN ('disponible', 'ocupada', 'reservada', 'mantenimiento')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

COMMENT ON TABLE public.mesas IS 'Catálogo de mesas físicas del restaurante, capacidad y disponibilidad';

-- ==============================================================================
-- 5. TABLA: RESERVAS (US-005, US-006, US-007, US-008)
-- ==============================================================================
CREATE TABLE IF NOT EXISTS public.reservas (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    cliente_id UUID NOT NULL REFERENCES public.clientes(id) ON DELETE CASCADE,
    mesa_id UUID NOT NULL REFERENCES public.mesas(id) ON DELETE RESTRICT,
    fecha DATE NOT NULL,
    hora TIME NOT NULL,
    cantidad_personas INTEGER NOT NULL CHECK (cantidad_personas > 0),
    estado VARCHAR(30) NOT NULL DEFAULT 'Pendiente' 
        CHECK (estado IN ('Pendiente', 'Confirmada', 'Atendida', 'Cancelada')),
    observaciones TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

COMMENT ON TABLE public.reservas IS 'Registro y control de reservas asignadas a clientes y mesas';

-- ==============================================================================
-- 6. TABLA: CATEGORÍAS (US-009 / Sprint 2)
-- ==============================================================================
CREATE TABLE IF NOT EXISTS public.categorias (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    nombre VARCHAR(50) NOT NULL UNIQUE,
    descripcion TEXT,
    estado BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

COMMENT ON TABLE public.categorias IS 'Clasificación de platos, bebidas y productos del menú';

-- ==============================================================================
-- 7. TABLA: PRODUCTOS / MENÚ (US-010 & US-011 / Sprint 2)
-- ==============================================================================
CREATE TABLE IF NOT EXISTS public.productos (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    categoria_id UUID NOT NULL REFERENCES public.categorias(id) ON DELETE RESTRICT,
    nombre VARCHAR(100) NOT NULL,
    descripcion TEXT,
    precio NUMERIC(10,2) NOT NULL CHECK (precio >= 0),
    disponible BOOLEAN NOT NULL DEFAULT TRUE,
    estado BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

COMMENT ON TABLE public.productos IS 'Catálogo oficial de platillos y bebidas con tarifas y disponibilidad';

-- ==============================================================================
-- 8. TABLA: DETALLES DE RESERVA / PREORDEN (US-006 / Sprint 2.2)
-- ==============================================================================
CREATE TABLE IF NOT EXISTS public.detalles_reserva (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    reserva_id UUID NOT NULL REFERENCES public.reservas(id) ON DELETE CASCADE,
    producto_id UUID NOT NULL REFERENCES public.productos(id) ON DELETE RESTRICT,
    cantidad INTEGER NOT NULL CHECK (cantidad >= 1),
    precio_unitario NUMERIC(10,2) NOT NULL CHECK (precio_unitario >= 0),
    subtotal NUMERIC(10,2) NOT NULL CHECK (subtotal >= 0),
    notas TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

COMMENT ON TABLE public.detalles_reserva IS 'Platillos y bebidas preordenados opcionalmente por el cliente para una reserva';

-- ==============================================================================
-- 9. TABLA: PEDIDOS / COMANDAS (US-012 / Sprint 2)
-- ==============================================================================
CREATE TABLE IF NOT EXISTS public.pedidos (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    mesa_id UUID NOT NULL REFERENCES public.mesas(id) ON DELETE RESTRICT,
    cliente_id UUID REFERENCES public.clientes(id) ON DELETE SET NULL,
    usuario_id UUID NOT NULL REFERENCES public.perfiles(id) ON DELETE RESTRICT,
    total NUMERIC(10,2) NOT NULL DEFAULT 0.00 CHECK (total >= 0),
    estado VARCHAR(30) NOT NULL DEFAULT 'Pendiente' 
        CHECK (estado IN ('Pendiente', 'En Preparación', 'Listo', 'Servido', 'Pagado', 'Cancelado')),
    observaciones TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

COMMENT ON TABLE public.pedidos IS 'Comandas y órdenes del punto de venta registradas para salón y cocina';

-- ==============================================================================
-- 10. TABLA: DETALLES DE PEDIDO (US-012 / Sprint 2)
