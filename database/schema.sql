-- ==================================================================================================
-- FUNCION RPC: registrar_salida_venta(p_pedido_id uuid)
-- Realiza de forma atómica la deducción de stock por venta, inserta movimientos en kardex y marca el pedido como Pagado
-- Requisitos:
--  * auth.uid() válido
--  * pedido en estado 'Servido'
--  * idempotencia: si ya existen movimientos kardex tipo 'salida_venta' para el pedido, no reprocesa
-- ==================================================================================================

CREATE OR REPLACE FUNCTION public.registrar_salida_venta(
    p_pedido_id uuid
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
    v_user_id uuid;
    v_pedido RECORD;
    v_det RECORD;
    v_inv RECORD;
    v_row RECORD;
    v_kardex_id uuid;
    v_kardex_ids uuid[] := ARRAY[]::uuid[];
BEGIN
    -- 1. Verificar autenticación
    v_user_id := auth.uid();
    IF v_user_id IS NULL THEN
        RAISE EXCEPTION 'No se ha detectado una sesión autenticada válida.';
    END IF;

    -- 2. Bloquear pedido
    SELECT * INTO v_pedido FROM public.pedidos WHERE id = p_pedido_id FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'El pedido especificado no existe.';
    END IF;

    -- 3. Permitir sólo pedidos en estado 'Servido'
    IF (v_pedido.estado IS NULL) OR (v_pedido.estado <> 'Servido') THEN
        RAISE EXCEPTION 'Solo se pueden procesar ventas para pedidos en estado Servido. Estado actual: %', v_pedido.estado;
    END IF;

    -- 4. Idempotencia: si ya existen movimientos de salida_venta para este pedido, no reprocesar
    IF EXISTS (SELECT 1 FROM public.kardex WHERE pedido_id = p_pedido_id AND tipo_movimiento = 'salida_venta') THEN
        RETURN jsonb_build_object('success', true, 'message', 'already_processed');
    END IF;

    -- 5. Recolectar y validar inventario: bloquear filas de inventario y verificar disponibilidad
    CREATE TEMP TABLE tmp_changes (
        inv_id uuid,
        producto_id uuid,
        cantidad integer,
        stock_anterior numeric,
        stock_posterior numeric,
        costo_unitario numeric
    ) ON COMMIT DROP;

    FOR v_det IN SELECT producto_id, cantidad FROM public.detalles_pedido WHERE pedido_id = p_pedido_id
    LOOP
        SELECT id, COALESCE(stock_actual, 0), COALESCE(costo_unitario, 0.00) INTO v_inv
        FROM public.inventario
        WHERE producto_id = v_det.producto_id
        FOR UPDATE;

        IF v_inv.id IS NULL THEN
            RAISE EXCEPTION 'El producto % no tiene registro de inventario.', v_det.producto_id;
        END IF;

        IF v_inv.stock_actual < v_det.cantidad THEN
            RAISE EXCEPTION 'Stock insuficiente para el producto %: disponible %, requerido %.', v_det.producto_id, v_inv.stock_actual, v_det.cantidad;
        END IF;

        INSERT INTO tmp_changes (inv_id, producto_id, cantidad, stock_anterior, stock_posterior, costo_unitario)
        VALUES (v_inv.id, v_det.producto_id, v_det.cantidad, v_inv.stock_actual, v_inv.stock_actual - v_det.cantidad, v_inv.costo_unitario);
    END LOOP;

    -- 6. Actualizar inventario e insertar kardex (append-only)
    FOR v_row IN SELECT * FROM tmp_changes
    LOOP
        UPDATE public.inventario
        SET stock_actual = v_row.stock_posterior,
            updated_at = NOW()
        WHERE id = v_row.inv_id;

        INSERT INTO public.kardex (
            producto_id,
            tipo_movimiento,
            cantidad,
            stock_anterior,
            stock_posterior,
            costo_unitario,
            motivo,
            usuario_id,
            compra_id,
            pedido_id,
            created_at
        ) VALUES (
            v_row.producto_id,
            'salida_venta',
            v_row.cantidad,
            v_row.stock_anterior,
            v_row.stock_posterior,
            v_row.costo_unitario,
            'Salida automática por venta',
            v_user_id,
            NULL,
            p_pedido_id,
            NOW()
        ) RETURNING id INTO v_kardex_id;

        v_kardex_ids := array_append(v_kardex_ids, v_kardex_id);
    END LOOP;

    -- 7. Marcar pedido como Pagado
    UPDATE public.pedidos
    SET estado = 'Pagado',
        updated_at = NOW()
    WHERE id = p_pedido_id;

    -- 8. Retornar resultado
    RETURN jsonb_build_object('success', true, 'kardex_ids', v_kardex_ids);

EXCEPTION WHEN OTHERS THEN
    -- Fallar limpiamente para que la transacción se revierta completamente
    RAISE;
END;
$$;

