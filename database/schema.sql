-- Función y Trigger para crear automáticamente el perfil al registrarse en Supabase Auth
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER AS $$
DECLARE
    default_rol_id BIGINT;
BEGIN
    -- Obtener rol_id desde metadata o asignar rol 1 (Administrador) si es el primero, sino 2 (Recepcionista)
    default_rol_id := COALESCE(
        (NEW.raw_user_meta_data->>'rol_id')::BIGINT, 
        1
    );

    INSERT INTO public.perfiles (id, rol_id, nombre, apellido, email, ci, telefono, estado)
    VALUES (
        NEW.id,
        default_rol_id,
        COALESCE(NEW.raw_user_meta_data->>'nombre', 'Usuario'),
        COALESCE(NEW.raw_user_meta_data->>'apellido', ''),
        NEW.email,
        COALESCE(NEW.raw_user_meta_data->>'ci', ''),
        COALESCE(NEW.raw_user_meta_data->>'telefono', ''),
        TRUE
    )
    ON CONFLICT (id) DO UPDATE SET
        nombre = EXCLUDED.nombre,
        apellido = EXCLUDED.apellido,
        email = EXCLUDED.email,
        ci = EXCLUDED.ci,
        telefono = EXCLUDED.telefono,
        rol_id = EXCLUDED.rol_id;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

